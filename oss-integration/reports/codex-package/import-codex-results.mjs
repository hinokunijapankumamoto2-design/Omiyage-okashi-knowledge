#!/usr/bin/env node
/**
 * Aggregates Codex review transcripts into CODEX_REVIEW_REPORT.md.
 *
 * Deliberately simple: it splits transcripts into findings and tabulates them.
 * It does NOT judge them. Every imported finding starts as UNVERIFIED, because
 * an unreviewed finding is not a fact — the verification pass is a human/Claude
 * step, recorded per finding afterwards.
 */
import { readFileSync, writeFileSync, existsSync, readdirSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '..', '..');
const resultsDir = resolve(root, 'reports', 'codex-results');

const SOURCES = {
  'standard-review.md': 'STANDARD',
  'adversarial-review.md': 'ADVERSARIAL',
  'benchmark-audit.md': 'BENCHMARK',
  'security-license-provenance-audit.md': 'SEC/LIC/PROV',
};

const SEVERITIES = ['CRITICAL', 'HIGH', 'MEDIUM', 'LOW', 'INFO'];

/** Splits a transcript on finding boundaries and pulls out the fields we tabulate. */
function parseFindings(text, source) {
  const out = [];
  // Codex writes fields in varying order: sometimes ID/SEVERITY precede FINDING,
  // sometimes FINDING comes first. Splitting on every label tears a single
  // finding into a header block and a body block, which silently loses the
  // severity. So: split on all labels, then merge forward any block that has no
  // finding statement of its own into the block that follows it.
  const raw = text
    .split(/\n(?=(?:#{1,4}\s*)?(?:ID|FINDING|CLAIM OR ASSUMPTION ATTACKED)\s*[:\n])/i)
    .map((b) => b.trim())
    .filter((b) => b.length > 0);

  const hasFinding = (b) => /(?:^|\n)\s*(?:#{1,4}\s*)?(?:FINDING|CLAIM OR ASSUMPTION ATTACKED)\s*[:\n]/i.test(b);
  const opensBlock = (b) => /^(?:#{1,4}\s*)?(?:ID|FINDING|CLAIM OR ASSUMPTION ATTACKED)\s*[:\n]/i.test(b);

  const blocks = [];
  let pending = '';
  for (const b of raw) {
    if (!opensBlock(b)) continue; // preamble or trailing prose, not a finding
    const merged = pending ? `${pending}\n${b}` : b;
    if (hasFinding(merged)) {
      blocks.push(merged);
      pending = '';
    } else {
      pending = merged; // a header awaiting its finding statement
    }
  }

  for (const block of blocks) {
    const field = (name) => {
      const m = new RegExp(`^\\s*(?:#{1,4}\\s*)?${name}\\s*[:\\n]\\s*(.+?)(?=\\n\\s*[A-Z][A-Z /]{2,}\\s*[:\\n]|$)`, 'ims').exec(block);
      return m ? m[1].trim().replace(/\s*\n\s*/g, ' ').slice(0, 400) : '';
    };
    const severity = (SEVERITIES.find((s) => new RegExp(`SEVERITY\\s*[:\\n]\\s*\\**${s}`, 'i').test(block)) ?? 'UNSPECIFIED');
    const finding = field('FINDING') || field('CLAIM OR ASSUMPTION ATTACKED');
    // No finding statement means this is not a finding, whatever else it holds.
    if (!finding) continue;
    out.push({
      source,
      severity,
      finding,
      evidence: field('EVIDENCE'),
      file: field('FILE') || field('FILE / LOCATION') || field('LINE / COMPONENT'),
      recommendation: field('RECOMMENDED ACTION') || field('FIX OR EXPERIMENT REQUIRED') || field('SUGGESTED FIX'),
      raw: block,
    });
  }
  return out;
}

const present = existsSync(resultsDir) ? readdirSync(resultsDir).filter((f) => f in SOURCES) : [];
if (present.length === 0) {
  console.error(
    `No Codex transcripts in ${resultsDir}.\n` +
      `Run reports/codex-package/RUN_CODEX_REVIEW.sh (or .ps1) in a Codex-connected\n` +
      `environment first. CODEX_REVIEW_REPORT.md left unchanged.`,
  );
  process.exit(1);
}

const findings = [];
for (const file of present) {
  findings.push(...parseFindings(readFileSync(resolve(resultsDir, file), 'utf8'), SOURCES[file]));
}
findings.sort((a, b) => SEVERITIES.indexOf(a.severity) - SEVERITIES.indexOf(b.severity));

const counts = Object.fromEntries(SEVERITIES.map((s) => [s, findings.filter((f) => f.severity === s).length]));
const missing = Object.keys(SOURCES).filter((f) => !present.includes(f));

const esc = (s) => (s || '—').replace(/\|/g, '\\|');
const rows = findings
  .map((f, i) => {
    const id = `CDX-${String(i + 1).padStart(3, '0')}`;
    return `| ${id} | ${f.source} | ${f.severity} | ${esc(f.finding)} | ${esc(f.evidence)} | ${esc(f.file)} | ${esc(f.recommendation)} | _pending_ | _pending_ | \`UNVERIFIED\` |`;
  })
  .join('\n');

const report = `# CODEX INDEPENDENT REVIEW REPORT

\`\`\`
CODEX_CONNECTION: PASS
CODEX REVIEW:     COMPLETED
IMPORTED:         ${new Date().toISOString().slice(0, 10)}
TRANSCRIPTS:      ${present.length}/4${missing.length ? ` (missing: ${missing.join(', ')})` : ''}
\`\`\`

Generated by \`reports/codex-package/import-codex-results.mjs\`. Raw transcripts
are in \`reports/codex-results/\` and are the evidence of record.

## Severity counts

| CRITICAL | HIGH | MEDIUM | LOW | INFO | UNSPECIFIED |
| --- | --- | --- | --- | --- | --- |
| ${counts.CRITICAL} | ${counts.HIGH} | ${counts.MEDIUM} | ${counts.LOW} | ${counts.INFO} | ${findings.filter((f) => f.severity === 'UNSPECIFIED').length} |

**Every finding below is \`UNVERIFIED\` on import.** A finding is not a fact
because Codex said it. Each must be independently reproduced and reclassified as
\`CONFIRMED\` / \`PARTIALLY_CONFIRMED\` / \`FALSE_POSITIVE\` / \`NOT_REPRODUCED\` /
\`OUT_OF_SCOPE\` / \`UNKNOWN\`, with evidence recorded either way. A false positive
is documented, not silently fixed.

## Release-blocker rule

Any **CRITICAL** or **HIGH** finding that verifies as \`CONFIRMED\` moves the ship
decision to \`DO_NOT_SHIP\` until fixed and re-verified. MEDIUM goes to v0.1 only
when it materially affects goal, security, benchmark validity or provenance —
otherwise \`V0.2_BACKLOG\`. LOW is v0.2 by default.

## Findings

| ID | Source | Severity | Finding | Evidence | File | Codex recommendation | Claude verification | Final decision | Status |
| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |
${rows || '| — | — | — | _No findings parsed. Check the transcripts by hand._ | — | — | — | — | — | — |'}

## Raw blocks

${findings.map((f, i) => `### CDX-${String(i + 1).padStart(3, '0')} · ${f.source} · ${f.severity}\n\n\`\`\`\n${f.raw.slice(0, 4000)}\n\`\`\``).join('\n\n')}
`;

const target = resolve(root, 'CODEX_REVIEW_REPORT.md');
writeFileSync(target, report, 'utf8');
console.log(`Imported ${findings.length} finding(s) from ${present.length} transcript(s) -> ${target}`);
console.log(`Severity: ${SEVERITIES.map((s) => `${s}=${counts[s]}`).join('  ')}`);
console.log('All findings marked UNVERIFIED. Reproduce each before any fix.');
